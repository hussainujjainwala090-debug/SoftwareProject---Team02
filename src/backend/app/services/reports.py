"""Report service (FR-15; UI-7, SD-2 steps 7-9).

Builds the PDF on the server, stores it in Cloud Storage (or the local store)
and returns a link that can be shared with an agronomist or other contact.
Reports(report_id, diagnosis_id, pdf_url, created_at).
"""
import io
import logging

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Image as RLImage
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.adapters.storage import Storage
from app.clock import Clock, to_iso
from app.repository import REPORTS, USERS, Repository, new_id
from app.services.forecast import ForecastService
from app.services.knowledge_base import KnowledgeBaseService
from app.services.scans import ScanService

log = logging.getLogger(__name__)
FOOTER = "Generated by AgriScan. Advisory only; confirm with an agronomist."


class ReportService:
    def __init__(self, repo: Repository, storage: Storage, scans: ScanService,
                 kb: KnowledgeBaseService, forecast: ForecastService, clock: Clock) -> None:
        self.repo = repo
        self.storage = storage
        self.scans = scans
        self.kb = kb
        self.forecast = forecast
        self.clock = clock

    def _photo(self, ref: str | None, caption: str):
        if not ref:
            return Paragraph(f"{caption}: not available", getSampleStyleSheet()["Normal"])
        try:
            data = self.storage.download(ref)
        except Exception as exc:  # a missing image should not stop the report
            log.warning("Could not load %s for report: %s", ref, exc)
            return Paragraph(f"{caption}: not available", getSampleStyleSheet()["Normal"])
        img = RLImage(io.BytesIO(data))
        ratio = img.imageHeight / img.imageWidth
        img.drawWidth, img.drawHeight = 7.5 * cm, 7.5 * cm * ratio
        return img

    def build_pdf(self, diagnosis: dict, scan: dict, farm: dict, created_at: str) -> bytes:
        styles = getSampleStyleSheet()
        body, h2 = styles["Normal"], styles["Heading2"]
        disease = self.kb.get(diagnosis["disease_id"]) if diagnosis["disease_id"] else None
        if diagnosis["status"] == "uncertain":
            label = "Uncertain"
        else:
            label = disease["name"] if disease else "Healthy"
        farmer = self.repo.get(USERS, scan["user_id"])
        weather = self.forecast.weather_by_id(diagnosis["weather_id"])

        story = [
            Paragraph("AgriScan Diagnosis Report", styles["Title"]),
            Paragraph(f"Date: {created_at[:10]}", body),
            Spacer(1, 0.4 * cm),
            Paragraph(f"Farm: {farm['name']}", body),
            Paragraph(f"Crop: {scan['crop_type'].replace('_', ' ').title()}", body),
            Paragraph(f"Farmer: {farmer['name'] if farmer else 'removed account'}", body),
            Paragraph(f"Scan taken: {scan['captured_at'].replace('T', ' ')[:16]} UTC", body),
            Spacer(1, 0.4 * cm),
            Table([[self._photo(scan["image_url"], "Original photo"),
                    self._photo(diagnosis["overlay_url"], "Highlighted area")],
                   [Paragraph("Original photo", body), Paragraph("Highlighted area", body)]],
                  colWidths=[8.5 * cm, 8.5 * cm]),
            Spacer(1, 0.4 * cm),
        ]
        severity = "-"
        if diagnosis["severity_level"]:
            severity = f"{diagnosis['severity_level'].title()} {diagnosis['affected_area_pct']:.0f}%"
        # After an agronomist review the model's score no longer describes the result.
        confidence = ("Agronomist review" if diagnosis["reviewed_by"]
                      else f"{diagnosis['confidence'] * 100:.0f}%")
        results = Table(
            [["Disease", "Confidence", "Severity", "Spread risk"],
             [label, confidence, severity,
              (diagnosis["spread_risk"] or "unavailable").title()]],
            colWidths=[5.5 * cm, 4 * cm, 3.5 * cm, 4 * cm])
        results.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8f0e3")),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]))
        story += [results, Spacer(1, 0.4 * cm), Paragraph("Recommended treatments", h2)]
        treatments = self.kb.treatments_for(disease["disease_id"]) if disease else []
        if not treatments:
            story.append(Paragraph("No treatment needed or the result needs review.", body))
        for t in treatments:
            story.append(Paragraph(f"<b>{t['type'].title()}:</b> {t['guidance']} "
                                   f"<i>Safety: {t['safety_warning']}</i>", body))
        story.append(Paragraph("Weather at the time of the scan", h2))
        if weather:
            story.append(Paragraph(f"{weather['temperature']:.0f} C, humidity {weather['humidity']:.0f}%, "
                                   f"rain {weather['rainfall']:.1f} mm", body))
        else:
            story.append(Paragraph("Weather data unavailable.", body))
        story += [Spacer(1, 0.8 * cm), Paragraph(f"<i>{FOOTER}</i>", body)]

        out = io.BytesIO()
        SimpleDocTemplate(out, pagesize=A4, title="AgriScan Diagnosis Report",
                          leftMargin=2 * cm, rightMargin=2 * cm).build(story)
        return out.getvalue()

    def generate(self, user: dict, diagnosis_id: str) -> dict:
        diagnosis, scan, farm = self.scans.load(user, diagnosis_id)
        created_at = to_iso(self.clock.now())
        pdf = self.build_pdf(diagnosis, scan, farm, created_at)
        report = {"report_id": new_id(), "diagnosis_id": diagnosis_id, "created_at": created_at,
                  "pdf_url": self.storage.upload("reports", pdf, "pdf", "application/pdf")}
        self.repo.create(REPORTS, report["report_id"], report)
        return self._out(report)

    def list_for(self, user: dict, diagnosis_id: str) -> list[dict]:
        self.scans.load(user, diagnosis_id)
        rows = sorted(self.repo.find(REPORTS, diagnosis_id=diagnosis_id),
                      key=lambda r: r["created_at"], reverse=True)
        return [self._out(r) for r in rows]

    def _out(self, report: dict) -> dict:
        return {**report, "pdf_url": self.storage.link(report["pdf_url"])}
